// header is the first line of every Go file the generator writes, in Go's generated-code form.
const header = "// Code generated by tscomfy-go. DO NOT EDIT.\n"

// The longest default a field comment shows, in runes; longer strings are cut.
const maxCommentDefault = 40

// generate returns the files for an export document (docs/spec.md §3.5), by name: for each
// template, <name>.json, the template indented, and <name>.go in package pkg.
func generate(pkg string, export []byte) (map[string][]byte, error) {
	raws, err := format.ParseExport(export)
	if err != nil {
		if _, ok := errors.AsType[*format.VersionError](err); ok {
			return nil, fmt.Errorf("the export wrote template %w: install the @tscomfy/go version that matches the tscomfy-go Go module", err)
		}
		return nil, fmt.Errorf("the export's output: %w", err)
	}
	decls := declarations{}
	files := make(map[string][]byte, 2*len(raws))
	for _, raw := range raws {
		indented := slices.Clone(raw)
		if err := indented.Indent(jsontext.WithIndent("  ")); err != nil {
			return nil, fmt.Errorf("the export's output: %w", err)
		}
		indented = append(indented, '\n')
		// workflow.Load is format.Parse: the file MustLoad embeds parses, so it can't panic.
		t, err := format.Parse(indented)
		if err != nil {
			return nil, err
		}
		if err := checkFileName(t.Name); err != nil {
			return nil, err
		}
		if _, taken := files[t.Name+".json"]; taken {
			return nil, fmt.Errorf("two templates are named %q", t.Name)
		}
		files[t.Name+".json"] = indented
		code, err := goFile(pkg, t, decls)
		if err != nil {
			return nil, err
		}
		files[t.Name+".go"] = code
	}
	return files, nil
}

// checkFileName refuses a template name whose Go file go build would skip on some platforms: a
// test file (_test), or one with a _GOOS or _GOARCH suffix. A file that matches on two platforms
// of different systems and architectures matches on all of them.
func checkFileName(name string) error {
	file := name + ".go"
	if strings.HasSuffix(name, "_test") {
		return fmt.Errorf("template %q: go build would take %s for a test file; rename the template", name, file)
	}
	for _, platform := range [][2]string{{"linux", "amd64"}, {"windows", "arm64"}} {
		ctx := build.Default
		ctx.GOOS, ctx.GOARCH = platform[0], platform[1]
		ctx.OpenFile = func(string) (io.ReadCloser, error) {
			return io.NopCloser(strings.NewReader("package p\n")), nil
		}
		if ok, err := ctx.MatchFile(".", file); err != nil || !ok {
			return fmt.Errorf("template %q: go build would compile %s for some systems or architectures only (a _GOOS or _GOARCH suffix); rename the template", name, file)
		}
	}
	return nil
}

// declarations are the package-level identifiers declared so far, with where each comes from.
type declarations map[string]string

func (d declarations) add(name, source string) error {
	if other, taken := d[name]; taken {
		return fmt.Errorf("%s and %s are both named %s", other, source, name)
	}
	d[name] = source
	return nil
}

type field struct {
	name, goType, comment string
}

type constant struct {
	name, id string
}

// goFile writes the Go file of one template (§6.2).
func goFile(pkg string, t *format.Template, decls declarations) ([]byte, error) {
	typ := goName(t.Name) // the name starts with a letter (format.Parse)
	if err := decls.add(typ, fmt.Sprintf("the type of template %q", t.Name)); err != nil {
		return nil, err
	}
	fieldNames := declarations{"Build": "the method Build"}
	fields := make([]field, len(t.Params))
	optional := false
	for i, p := range t.Params {
		goType, err := fieldType(p)
		if err != nil {
			return nil, fmt.Errorf("template %q, parameter %q: %w", t.Name, p.Name, err)
		}
		name := goName(p.Name)
		if err := fieldNames.add(name, fmt.Sprintf("the field of parameter %q", p.Name)); err != nil {
			return nil, fmt.Errorf("template %q: %w", t.Name, err)
		}
		fields[i] = field{name: name, goType: goType, comment: fieldComment(p)}
		optional = optional || p.Optional
	}
	var consts []constant
	for _, id := range t.Nodes {
		if automatic(id) {
			continue
		}
		part := goName(id)
		if part == "" {
			return nil, fmt.Errorf("template %q: node id %q gives no Go identifier", t.Name, id)
		}
		name := typ + part
		if err := decls.add(name, fmt.Sprintf("the constant of node %q of template %q", id, t.Name)); err != nil {
			return nil, err
		}
		consts = append(consts, constant{name: name, id: id})
	}

	var b bytes.Buffer
	b.WriteString(header)
	fmt.Fprintf(&b, "\npackage %s\n\n", pkg)
	b.WriteString("import (\n\t_ \"embed\"\n\n\t\"github.com/TheeKia/tscomfy-go/comfy\"\n\t\"github.com/TheeKia/tscomfy-go/workflow\"\n)\n\n")
	raw, tmpl := unexported(typ)+"JSON", unexported(typ)+"Template"
	fmt.Fprintf(&b, "//go:embed %s.json\nvar %s []byte\n\n", t.Name, raw)
	fmt.Fprintf(&b, "var %s = workflow.MustLoad(%s)\n\n", tmpl, raw)
	if len(fields) == 0 {
		fmt.Fprintf(&b, "// %s is the %s workflow, which has no parameters.\ntype %s struct{}\n\n", typ, t.Name, typ)
		fmt.Fprintf(&b, "// Build returns the %s prompt.\nfunc (%s) Build() (comfy.Prompt, error) {\n\treturn %s.Fill()\n}\n", t.Name, typ, tmpl)
	} else {
		fmt.Fprintf(&b, "// %s holds the parameters of the %s workflow.", typ, t.Name)
		if optional {
			b.WriteString(" Optional fields left\n// nil keep the value written in the workflow.")
		}
		fmt.Fprintf(&b, "\ntype %s struct {\n", typ)
		for _, f := range fields {
			fmt.Fprintf(&b, "\t%s %s // %s\n", f.name, f.goType, f.comment)
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "// Build returns the %s prompt with p's values. It reports a value outside its\n", t.Name)
		b.WriteString("// input's bounds, a float that isn't finite or a string that isn't valid UTF-8\n")
		b.WriteString("// as a *workflow.ParamError; the server validates the rest.\n")
		names := make([]string, len(fields))
		for i, f := range fields {
			names[i] = "p." + f.name
		}
		fmt.Fprintf(&b, "func (p %s) Build() (comfy.Prompt, error) {\n\treturn %s.Fill(%s)\n}\n", typ, tmpl, strings.Join(names, ", "))
	}
	if len(consts) > 0 {
		fmt.Fprintf(&b, "\n// The %s nodes, by the ids given in the workflow.\nconst (\n", t.Name)
		for _, c := range consts {
			fmt.Fprintf(&b, "\t%s comfy.NodeID = %s\n", c.name, strconv.Quote(c.id))
		}
		b.WriteString(")\n")
	}
	code, err := goformat.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("template %q: formatting the Go file: %w", t.Name, err)
	}
	return code, nil
}

var (
	minInt32  = big.NewInt(math.MinInt32)
	maxInt32  = big.NewInt(math.MaxInt32)
	minInt64  = big.NewInt(math.MinInt64)
	maxInt64  = big.NewInt(math.MaxInt64)
	maxUint64 = new(big.Int).SetUint64(math.MaxUint64)
)

// fieldType is the Go type of a parameter's field (§6.3); a pointer for an optional one.
func fieldType(p format.Param) (string, error) {
	var typ string
	switch p.Kind {
	case format.KindString, format.KindCombo:
		typ = "string"
	case format.KindBoolean:
		typ = "bool"
	case format.KindFloat:
		typ = "float64"
	case format.KindInt:
		var err error
		if typ, err = intType(p.Min.Int, p.Max.Int); err != nil {
			return "", err
		}
	}
	if p.Optional {
		return "*" + typ, nil
	}
	return typ, nil
}

// intType picks the Go type of an int parameter from its bounds, nil when absent: int when both
// fit 32 bits, uint64 when the range is non-negative and reaches beyond int64, int64 when every
// bound given fits it.
func intType(lo, hi *big.Int) (string, error) {
	within := func(n, from, to *big.Int) bool { return n.Cmp(from) >= 0 && n.Cmp(to) <= 0 }
	switch {
	case lo != nil && hi != nil && within(lo, minInt32, maxInt32) && within(hi, minInt32, maxInt32):
		return "int", nil
	case lo != nil && hi != nil && lo.Sign() >= 0 && hi.Cmp(maxInt64) > 0 && hi.Cmp(maxUint64) <= 0:
		return "uint64", nil
	case (lo == nil || within(lo, minInt64, maxInt64)) && (hi == nil || within(hi, minInt64, maxInt64)):
		return "int64", nil
	default:
		return "", fmt.Errorf("the bounds %s fit neither int64 nor uint64", bounds(lo, hi))
	}
}

func bounds(lo, hi *big.Int) string {
	switch {
	case lo != nil && hi != nil:
		return lo.String() + " to " + hi.String()
	case lo != nil:
		return "from " + lo.String()
	default:
		return "up to " + hi.String()
	}
}

// fieldComment says where a parameter goes, its bounds, and an optional one's default.
func fieldComment(p format.Param) string {
	parts := []string{commentText(p.Node) + "." + commentText(p.Input)}
	switch {
	case p.Min.Set() && p.Max.Set():
		parts = append(parts, fmt.Sprintf("%s to %s", p.Min.Literal, p.Max.Literal))
	case p.Min.Set():
		parts = append(parts, fmt.Sprintf("at least %s", p.Min.Literal))
	case p.Max.Set():
		parts = append(parts, fmt.Sprintf("at most %s", p.Max.Literal))
	}
	if p.Optional {
		parts = append(parts, "default "+commentValue(p.Default))
	}
	return strings.Join(parts, ", ")
}

// commentValue is a JSON literal as a comment shows it: strings longer than maxCommentDefault
// runes are cut, with an ellipsis.
func commentValue(literal jsontext.Value) string {
	if literal.Kind() != '"' {
		return string(literal)
	}
	var s string
	if b, err := jsontext.AppendUnquote(nil, literal); err == nil {
		s = string(b)
	}
	if utf8.RuneCountInString(s) <= maxCommentDefault {
		return string(literal)
	}
	runes := []rune(s)[:maxCommentDefault]
	quoted, err := jsontext.AppendQuote(nil, string(runes))
	if err != nil {
		return string(literal)
	}
	return string(quoted[:len(quoted)-1]) + `…"`
}

// commentText is a name as a comment can hold it: as is when it is all printable, quoted
// otherwise, so a newline in a node id can't end the comment.
func commentText(s string) string {
	for _, r := range s {
		if !unicode.IsPrint(r) {
			return strconv.Quote(s)
		}
	}
	return s
}
